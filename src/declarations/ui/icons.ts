// Widened for any icon component
export type LucideIcon = ComponentType<{ className?: string } & Record<string, unknown>>

interface Look {
  weight?: IconWeight
  // Tailwind colour class painted on the icon
  tone?: string
}

/**
 * Phosphor icon wearing a fixed weight and colour
 * @param {Icon} Base - Phosphor icon
 * @param {Look} [look] - Weight and colour
 * @return {LucideIcon}
 */

const phosphor = (Base: Icon, look: Look = {}): LucideIcon => {
  const Painted: LucideIcon = ({ className, ...rest }) =>
    createElement(Base, {
      ...rest,
      weight: look.weight,
      className: cn(className, look.tone),
    })

  return Painted
}

