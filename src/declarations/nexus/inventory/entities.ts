/**
 * How far a command may go on an entity
 * @type {readonly string[]}
 */

export const NEXUS_EXPOSURES = ['full', 'readOnly', 'excluded'] as const

export type NexusExposure = (typeof NEXUS_EXPOSURES)[number]

/**
 * Decision taken on one data model
 * @typedef {Object} EntityEntry
 * @property {string} model - Prisma model name
 * @property {NexusExposure} exposure - Reach of the commands
 * @property {string} [reason] - Why it is not fully exposed
 * @property {string} display - Readable column
 * @property {string[]} search - Text search columns
 * @property {string[]} [hidden] - Columns masked on top of the general rules
 * @property {string} [alias] - Short command name
 */

export interface EntityEntry {
  model: string
  exposure: NexusExposure
  reason?: string
  display: string
  search: string[]
  hidden?: string[]
  alias?: string
}

