/**
 * Seconds in a minute
 * @type {number}
 */

export const MINUTE_SECONDS = 60

/**
 * Seconds in an hour
 * @type {number}
 */

export const HOUR_SECONDS = 60 * MINUTE_SECONDS

/**
 * Seconds in a day
 * @type {number}
 */

export const DAY_SECONDS = 24 * HOUR_SECONDS

/**
 * Seconds in a week
 * @type {number}
 */

export const WEEK_SECONDS = 7 * DAY_SECONDS

/**
 * Milliseconds in a second
 * @type {number}
 */

export const SECOND_MS = 1000

/**
 * Milliseconds in a minute
 * @type {number}
 */

export const MINUTE_MS = MINUTE_SECONDS * SECOND_MS

/**
 * Milliseconds in an hour
 * @type {number}
 */

export const HOUR_MS = HOUR_SECONDS * SECOND_MS

/**
 * Milliseconds in a day
 * @type {number}
 */

export const DAY_MS = DAY_SECONDS * SECOND_MS

/**
 * Milliseconds in a week
 * @type {number}
 */

export const WEEK_MS = WEEK_SECONDS * SECOND_MS

/**
 * Microseconds in a millisecond
 * @type {number}
 */

export const MICROSECONDS_PER_MS = 1000
