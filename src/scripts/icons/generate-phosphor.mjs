import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { resolve } from 'node:path'

// Registry read, data written
const REGISTRY = 'src/declarations/ui/icons.ts'
const OUTPUT = 'src/declarations/ui/phosphor.ts'
const DEFS = 'node_modules/@phosphor-icons/react/dist/defs'
const DEFAULT_WEIGHT = 'regular'

const source = readFileSync(REGISTRY, 'utf8')

// Named looks of the registry
const looks = Object.fromEntries(
  [...source.matchAll(/const (\w+): Look = \{ weight: '(\w+)' \}/g)].map(([, name, weight]) => [
    name,
    weight,
  ])
)

/**
 * Weight named by a look
 * @param {string} [look] - Look argument
 * @return {string} - Weight
 */

const weightOf = (look = '') =>
  look.match(/weight: '(\w+)'/)?.[1] ?? looks[look.trim()] ?? DEFAULT_WEIGHT

// Weights asked per icon
const wanted = new Map()
for (const [, name, look] of source.matchAll(/phosphor\((\w+)(?:,\s*([^)]*))?\)/g)) {
  wanted.set(name, new Set([...(wanted.get(name) ?? []), weightOf(look)]))
}

/**
 * Shapes of one drawn weight
 * @param {{ props: { children: unknown } }} drawing - Weight fragment
 * @return {Array<[string, Record<string, unknown>]>} - Tag and attributes
 */

const shapesOf = (drawing) =>
  [drawing.props.children].flat().map((shape) => [shape.type, shape.props])

const lines = []
for (const name of [...wanted.keys()].sort()) {
  const { default: weights } = await import(pathToFileURL(resolve(DEFS, `${name}.es.js`)).href)
  const kept = [...wanted.get(name)].sort().map((weight) => [weight, shapesOf(weights.get(weight))])
  lines.push(`export const ${name} = phosphorIcon('${name}Icon', ${JSON.stringify(Object.fromEntries(kept))})`)
}

writeFileSync(
  OUTPUT,
  `// Generated by src/scripts/icons/generate-phosphor.mjs\nimport { phosphorIcon } from '@/components/elements/display/glyphs/phosphorIcon'\n\n${lines.join('\n')}\n`
)
console.log(`${lines.length} icons written to ${OUTPUT}`)
